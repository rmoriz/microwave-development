"""Load and render the claim inventory in ``docs/claims.toml``.

The inventory is the single source of truth for what this repository says
about itself. ``render_doc`` turns open gaps into ``docs/remaining-work.md``
and ``render_block`` turns the counts into the marked README region. Only the
renderer writes either region.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from pathlib import Path
import re
import tomllib

AREAS = (
    "deployment",
    "migration",
    "mail",
    "search",
    "depsolver",
    "ha",
    "auth",
    "tooling",
    "docs",
    "website",
)
STATUSES = ("verified", "gap", "manual")
KINDS = ("file", "grep", "absent", "cargo", "npm", "manual")

DOC_START = "<!-- Generated by scripts/render-remaining-work.py. Edit docs/claims.toml, not this file. -->"
DOC_END = "<!-- end of generated remaining work -->"

ID_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
LINK_RE = re.compile(r"[\w./~-]*remaining-work\.md#[a-z0-9-]+")
GAP_CLAIM_RE = re.compile(r"claim:\s*'([a-z0-9-]+)'")
MANUAL_DAYS = 90

# Every prose surface must be owned by at least one claim.
COVERAGE_PATTERNS = (
    "README.md",
    "TODO.md",
    "docs/*.md",
    "website/homepage/src/pages/**/*",
    "website/homepage/src/components/**/*",
    "website/homepage/src/data/**/*",
)
LINK_SURFACES = ("README.md", "docs/*.md", "website/homepage/src/**/*")

BLOCK_START = "<!-- generated:remaining-work:start -->"
BLOCK_END = "<!-- generated:remaining-work:end -->"

_CLAIM_FIELDS = {"id", "summary", "area", "status", "surfaces", "verify"}
_SURFACE_FIELDS = {"path", "needle"}
_VERIFY_FIELDS = {"kind", "path", "pattern", "test", "checked", "ref"}


@dataclass(slots=True)
class Surface:
    """A place where a claim is made, plus the literal text that makes it."""

    path: str
    needle: str | None = None


@dataclass(slots=True)
class Verify:
    """How a claim is checked."""

    kind: str
    path: str | None = None
    pattern: str | None = None
    test: str | None = None
    checked: date | None = None
    ref: str | None = None


@dataclass(slots=True)
class Claim:
    """One factual statement, the surfaces that make it, and its check."""

    id: str
    summary: str
    area: str
    status: str
    surfaces: list[Surface]
    verify: Verify


def _table(value: object, where: str, allowed: set[str]) -> dict:
    if not isinstance(value, dict):
        raise ValueError(f"{where}: expected a table, got {type(value).__name__}")
    unknown = set(value) - allowed
    if unknown:
        raise ValueError(f"{where}: unknown field(s) {', '.join(sorted(unknown))}")
    return value


def _string(table: dict, key: str, where: str, required: bool = True) -> str | None:
    if key not in table:
        if required:
            raise ValueError(f"{where}: missing field {key!r}")
        return None
    value = table[key]
    if not isinstance(value, str):
        raise ValueError(f"{where}.{key}: expected a string, got {type(value).__name__}")
    return value


def _parse_surface(raw: object, where: str) -> Surface:
    table = _table(raw, where, _SURFACE_FIELDS)
    path = _string(table, "path", where)
    needle = _string(table, "needle", where, required=False)
    return Surface(path, needle or None)


def _parse_verify(raw: object, where: str) -> Verify:
    table = _table(raw, where, _VERIFY_FIELDS)
    kind = _string(table, "kind", where)
    checked = table.get("checked")
    if checked is not None and not isinstance(checked, date):
        raise ValueError(f"{where}.checked: expected a date, got {type(checked).__name__}")
    return Verify(
        kind,
        path=_string(table, "path", where, required=False),
        pattern=_string(table, "pattern", where, required=False),
        test=_string(table, "test", where, required=False),
        checked=checked,
        ref=_string(table, "ref", where, required=False),
    )


def _parse_claim(raw: object, where: str) -> Claim:
    table = _table(raw, where, _CLAIM_FIELDS)
    surfaces = table.get("surfaces")
    if not isinstance(surfaces, list):
        raise ValueError(f"{where}.surfaces: expected an array of tables")
    if "verify" not in table:
        raise ValueError(f"{where}: missing field 'verify'")
    return Claim(
        id=_string(table, "id", where),
        summary=_string(table, "summary", where),
        area=_string(table, "area", where),
        status=_string(table, "status", where),
        surfaces=[_parse_surface(s, f"{where}.surfaces[{i}]") for i, s in enumerate(surfaces)],
        verify=_parse_verify(table["verify"], f"{where}.verify"),
    )


def load_claims(path: Path) -> list[Claim]:
    """Parse an inventory file, rejecting unknown fields and wrong types."""

    data = tomllib.loads(path.read_text(encoding="utf-8"))
    unknown = set(data) - {"version", "claim"}
    if unknown:
        raise ValueError(f"{path}: unknown field(s) {', '.join(sorted(unknown))}")
    if data.get("version") != 1:
        raise ValueError(f"{path}: expected version = 1")
    claims = data.get("claim", [])
    if not isinstance(claims, list):
        raise ValueError(f"{path}: claim must be an array of tables")
    return [_parse_claim(raw, f"{path}: claim[{i}]") for i, raw in enumerate(claims)]


def _gaps_by_area(claims: list[Claim]) -> dict[str, list[Claim]]:
    groups: dict[str, list[Claim]] = {area: [] for area in AREAS}
    for claim in sorted(claims, key=lambda c: (AREAS.index(c.area) if c.area in AREAS else len(AREAS), c.id)):
        if claim.status == "gap":
            groups.setdefault(claim.area, []).append(claim)
    return {area: found for area, found in groups.items() if found}


def _counts(claims: list[Claim]) -> tuple[int, str]:
    groups = _gaps_by_area(claims)
    total = sum(len(found) for found in groups.values())
    detail = ", ".join(f"{area}: {len(found)}" for area, found in groups.items())
    return total, detail


def render_doc(claims: list[Claim]) -> str:
    """Render the gap list: grouped by area, newest inventory order, anchored."""

    total, detail = _counts(claims)
    lines = [DOC_START, "", "# Remaining work", "", f"Open gaps: {total}" + (f" ({detail})" if detail else ""), ""]
    if not total:
        lines.append("Every inventoried claim is verified.")
    for area, found in _gaps_by_area(claims).items():
        lines += [f'<a id="area-{area}"></a>', "", f"## {area.title()}", ""]
        for claim in found:
            lines += [f'<a id="{claim.id}"></a>', "", f"**{claim.id}** — {claim.summary}", ""]
            for surface in claim.surfaces:
                lines.append(f"- `{surface.path}`")
            lines.append("")
    lines.append(DOC_END)
    return "\n".join(lines) + "\n"


def render_block(claims: list[Claim]) -> str:
    """Render the marked README summary block."""

    total, detail = _counts(claims)
    groups = _gaps_by_area(claims)
    links = ", ".join(f"[{area}](docs/remaining-work.md#area-{area})" for area in groups)
    body = f"Open gaps: {total}" + (f" ({detail})" if detail else "")
    if links:
        body += f". By area: {links}."
    return "\n".join([BLOCK_START, body, BLOCK_END])


def replace_block(text: str, block: str) -> str:
    """Replace the marked region in ``text`` with ``block``."""

    for marker in (BLOCK_START, BLOCK_END):
        found = text.count(marker)
        if found != 1:
            raise ValueError(f"{marker} must appear exactly once, found {found}")
    start = text.index(BLOCK_START)
    end = text.index(BLOCK_END) + len(BLOCK_END)
    return text[:start] + block + text[end:]


def _inside(root: Path, path: str) -> tuple[Path | None, str | None]:
    """Resolve ``path`` against ``root``, rejecting absolute and escaping paths."""

    candidate = Path(path)
    if candidate.is_absolute():
        return None, f"must be relative to the repository root: {path}"
    resolved = (candidate if not path else (root / candidate)).resolve()
    if resolved != root.resolve() and root.resolve() not in resolved.parents:
        return None, f"escapes the repository root: {path}"
    return resolved, None


def _validate_surface(root: Path, claim_id: str, surface: Surface) -> list[str]:
    errors = []
    if not surface.path:
        return [f"?{claim_id}: surface without a path"]
    target, problem = _inside(root, surface.path)
    if problem:
        return [f"{surface.path}:{claim_id}: {problem}"]
    if not target.is_file():
        return [f"{surface.path}:{claim_id}: surface file does not exist"]
    if not surface.needle:
        return [f"{surface.path}:{claim_id}: surface needs a non-empty needle"]
    if surface.needle not in target.read_text(encoding="utf-8", errors="replace"):
        errors.append(f"{surface.path}:{claim_id}: needle not found: {surface.needle}")
    return errors


def _validate_verify(root: Path, claim: Claim, today: date) -> list[str]:
    verify = claim.verify
    claim_id = claim.id
    rel = verify.path or verify.ref or "?"

    if verify.kind not in KINDS:
        return [f"{rel}:{claim_id}: unknown verify kind {verify.kind!r}"]

    if verify.kind == "manual":
        if verify.checked is None:
            return [f"{rel}:{claim_id}: manual verify needs a checked date"]
        age = (today - verify.checked).days
        errors = []
        if age > MANUAL_DAYS:
            errors.append(f"{rel}:{claim_id}: expired, checked {verify.checked} ({age} days ago, limit {MANUAL_DAYS})")
        if not verify.ref:
            errors.append(f"{rel}:{claim_id}: manual verify needs a ref")
        else:
            target, problem = _inside(root, verify.ref)
            if problem:
                errors.append(f"{verify.ref}:{claim_id}: {problem}")
            elif not target.is_file():
                errors.append(f"{verify.ref}:{claim_id}: ref does not exist")
        return errors

    if not verify.path:
        return [f"{rel}:{claim_id}: verify of kind {verify.kind!r} needs a path"]
    target, problem = _inside(root, verify.path)
    if problem:
        return [f"{verify.path}:{claim_id}: {problem}"]
    if not target.is_file():
        return [f"{verify.path}:{claim_id}: verify target does not exist"]

    if verify.kind == "file":
        return []
    if verify.kind == "npm":
        return []
    if verify.kind in ("grep", "absent"):
        if not verify.pattern:
            return [f"{verify.path}:{claim_id}: {verify.kind} verify needs a pattern"]
        try:
            pattern = re.compile(verify.pattern)
        except re.error as error:
            return [f"{verify.path}:{claim_id}: pattern does not compile: {error}"]
        matched = pattern.search(target.read_text(encoding="utf-8", errors="replace"))
        if verify.kind == "grep" and not matched:
            return [f"{verify.path}:{claim_id}: pattern does not match: {verify.pattern}"]
        if verify.kind == "absent" and matched:
            return [f"{verify.path}:{claim_id}: pattern should not match: {verify.pattern}"]
        return []

    # cargo: the file exists and names the test after the `::` separator.
    if not verify.test or "::" not in verify.test:
        return [f"{verify.path}:{claim_id}: cargo verify needs a test name like module::test"]
    name = verify.test.split("::", 1)[1]
    body = target.read_text(encoding="utf-8", errors="replace")
    if not re.search(rf"\bfn\s+{re.escape(name)}\b", body):
        return [f"{verify.path}:{claim_id}: test {name!r} not found in the file"]
    return []


def validate(claims: list[Claim], root: Path, today: date) -> list[str]:
    """Check the inventory itself and every surface and verify target."""

    errors: list[str] = []
    seen: set[str] = set()
    for claim in claims:
        if not ID_RE.match(claim.id):
            errors.append(f"?{claim.id}: id must match {ID_RE.pattern}")
        if claim.id in seen:
            errors.append(f"?{claim.id}: duplicate id")
        seen.add(claim.id)
        if claim.area not in AREAS:
            errors.append(f"?{claim.id}: unknown area {claim.area!r}")
        if claim.status not in STATUSES:
            errors.append(f"?{claim.id}: unknown status {claim.status!r}")
        if not claim.summary.strip():
            errors.append(f"?{claim.id}: empty summary")
        if claim.status == "gap" and not claim.surfaces:
            errors.append(f"?{claim.id}: a gap needs at least one surface")
        for surface in claim.surfaces:
            errors += _validate_surface(root, claim.id, surface)
        errors += _validate_verify(root, claim, today)

    order = {area: index for index, area in enumerate(AREAS)}
    return sorted(errors, key=lambda e: (order.get(_area_of(e, claims), len(AREAS)), e))


def _area_of(error: str, claims: list[Claim]) -> str:
    for claim in claims:
        if error.startswith(f"?{claim.id}:") or f":{claim.id}:" in error:
            return claim.area
    return ""


def _expand(root: Path, patterns: tuple[str, ...]) -> list[Path]:
    found: list[Path] = []
    for pattern in patterns:
        found += [p for p in root.glob(pattern) if p.is_file()]
    return found


def coverage_gaps(claims: list[Claim], root: Path) -> list[str]:
    """List prose files no claim owns."""

    covered = {surface.path for claim in claims for surface in claim.surfaces}
    skip = {"docs/claims.toml", "docs/remaining-work.md"}
    gaps = []
    for path in _expand(root, COVERAGE_PATTERNS):
        rel = path.relative_to(root).as_posix()
        if rel in skip or rel.startswith("docs/superpowers/"):
            continue
        if rel not in covered:
            gaps.append(rel)
    return sorted(gaps)


def link_errors(claims: list[Claim], root: Path) -> list[str]:
    """Report `remaining-work.md#<id>` links that miss the file or the inventory."""

    # `area-<area>` anchors are generated by the renderer, not claim ids.
    known = {claim.id for claim in claims} | {f"area-{area}" for area in AREAS}
    target_doc = (root / "docs" / "remaining-work.md").resolve()
    errors = []
    for path in _expand(root, LINK_SURFACES):
        rel = path.relative_to(root).as_posix()
        website = rel.startswith("website/")
        for line_no, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            for link, fragment in (found.rsplit("#", 1) for found in LINK_RE.findall(line)):
                if (path.parent / link).resolve() != target_doc:
                    errors.append(f"{rel}:{line_no}: {link} does not resolve to docs/remaining-work.md")
                if fragment not in known:
                    errors.append(f"{rel}:{line_no}: link to unknown claim id {fragment!r}")
            if not website:
                continue
            for found in GAP_CLAIM_RE.findall(line):
                if found not in known:
                    errors.append(f"{rel}:{line_no}: unknown gap claim id {found!r}")
    return errors


def render_errors(claims: list[Claim], root: Path) -> list[str]:
    """Report generated files that differ from the inventory."""

    errors = []
    doc = root / "docs" / "remaining-work.md"
    rendered = render_doc(claims)
    if not doc.is_file():
        errors.append("docs/remaining-work.md: missing, run scripts/render-remaining-work.py")
    elif doc.read_text(encoding="utf-8") != rendered:
        errors.append("docs/remaining-work.md: stale, run scripts/render-remaining-work.py")

    readme = root / "README.md"
    if not readme.is_file():
        return errors + ["README.md: missing"]
    try:
        expected = replace_block(readme.read_text(encoding="utf-8"), render_block(claims))
    except ValueError as error:
        return errors + [f"README.md: {error}"]
    if expected != readme.read_text(encoding="utf-8"):
        errors.append("README.md: generated block is stale, run scripts/render-remaining-work.py")
    return errors
