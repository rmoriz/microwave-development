"""Load and render the claim inventory in ``docs/claims.toml``.

The inventory is the single source of truth for what this repository says
about itself. ``render_doc`` turns open gaps into ``docs/remaining-work.md``
and ``render_block`` turns the counts into the marked README region. Only the
renderer writes either region.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from pathlib import Path
import tomllib

AREAS = (
    "deployment",
    "migration",
    "mail",
    "search",
    "ha",
    "auth",
    "tooling",
    "docs",
    "website",
)
STATUSES = ("verified", "gap", "manual")
KINDS = ("file", "grep", "cargo", "npm", "manual")

DOC_START = "<!-- Generated by scripts/render-remaining-work.py. Edit docs/claims.toml, not this file. -->"
DOC_END = "<!-- end of generated remaining work -->"

BLOCK_START = "<!-- generated:remaining-work:start -->"
BLOCK_END = "<!-- generated:remaining-work:end -->"

_CLAIM_FIELDS = {"id", "summary", "area", "status", "surfaces", "verify"}
_SURFACE_FIELDS = {"path", "needle"}
_VERIFY_FIELDS = {"kind", "path", "pattern", "test", "checked", "ref"}


@dataclass(slots=True)
class Surface:
    """A place where a claim is made, plus the literal text that makes it."""

    path: str
    needle: str | None = None


@dataclass(slots=True)
class Verify:
    """How a claim is checked."""

    kind: str
    path: str | None = None
    pattern: str | None = None
    test: str | None = None
    checked: date | None = None
    ref: str | None = None


@dataclass(slots=True)
class Claim:
    """One factual statement, the surfaces that make it, and its check."""

    id: str
    summary: str
    area: str
    status: str
    surfaces: list[Surface]
    verify: Verify


def _table(value: object, where: str, allowed: set[str]) -> dict:
    if not isinstance(value, dict):
        raise ValueError(f"{where}: expected a table, got {type(value).__name__}")
    unknown = set(value) - allowed
    if unknown:
        raise ValueError(f"{where}: unknown field(s) {', '.join(sorted(unknown))}")
    return value


def _string(table: dict, key: str, where: str, required: bool = True) -> str | None:
    if key not in table:
        if required:
            raise ValueError(f"{where}: missing field {key!r}")
        return None
    value = table[key]
    if not isinstance(value, str):
        raise ValueError(f"{where}.{key}: expected a string, got {type(value).__name__}")
    return value


def _parse_surface(raw: object, where: str) -> Surface:
    table = _table(raw, where, _SURFACE_FIELDS)
    path = _string(table, "path", where)
    needle = _string(table, "needle", where, required=False)
    return Surface(path, needle or None)


def _parse_verify(raw: object, where: str) -> Verify:
    table = _table(raw, where, _VERIFY_FIELDS)
    kind = _string(table, "kind", where)
    checked = table.get("checked")
    if checked is not None and not isinstance(checked, date):
        raise ValueError(f"{where}.checked: expected a date, got {type(checked).__name__}")
    return Verify(
        kind,
        path=_string(table, "path", where, required=False),
        pattern=_string(table, "pattern", where, required=False),
        test=_string(table, "test", where, required=False),
        checked=checked,
        ref=_string(table, "ref", where, required=False),
    )


def _parse_claim(raw: object, where: str) -> Claim:
    table = _table(raw, where, _CLAIM_FIELDS)
    surfaces = table.get("surfaces")
    if not isinstance(surfaces, list):
        raise ValueError(f"{where}.surfaces: expected an array of tables")
    if "verify" not in table:
        raise ValueError(f"{where}: missing field 'verify'")
    return Claim(
        id=_string(table, "id", where),
        summary=_string(table, "summary", where),
        area=_string(table, "area", where),
        status=_string(table, "status", where),
        surfaces=[_parse_surface(s, f"{where}.surfaces[{i}]") for i, s in enumerate(surfaces)],
        verify=_parse_verify(table["verify"], f"{where}.verify"),
    )


def load_claims(path: Path) -> list[Claim]:
    """Parse an inventory file, rejecting unknown fields and wrong types."""

    data = tomllib.loads(path.read_text(encoding="utf-8"))
    unknown = set(data) - {"version", "claim"}
    if unknown:
        raise ValueError(f"{path}: unknown field(s) {', '.join(sorted(unknown))}")
    if data.get("version") != 1:
        raise ValueError(f"{path}: expected version = 1")
    claims = data.get("claim", [])
    if not isinstance(claims, list):
        raise ValueError(f"{path}: claim must be an array of tables")
    return [_parse_claim(raw, f"{path}: claim[{i}]") for i, raw in enumerate(claims)]


def _gaps_by_area(claims: list[Claim]) -> dict[str, list[Claim]]:
    groups: dict[str, list[Claim]] = {area: [] for area in AREAS}
    for claim in sorted(claims, key=lambda c: (AREAS.index(c.area) if c.area in AREAS else len(AREAS), c.id)):
        if claim.status == "gap":
            groups.setdefault(claim.area, []).append(claim)
    return {area: found for area, found in groups.items() if found}


def _counts(claims: list[Claim]) -> tuple[int, str]:
    groups = _gaps_by_area(claims)
    total = sum(len(found) for found in groups.values())
    detail = ", ".join(f"{area}: {len(found)}" for area, found in groups.items())
    return total, detail


def render_doc(claims: list[Claim]) -> str:
    """Render the gap list: grouped by area, newest inventory order, anchored."""

    total, detail = _counts(claims)
    lines = [DOC_START, "", "# Remaining work", "", f"Open gaps: {total}" + (f" ({detail})" if detail else ""), ""]
    if not total:
        lines.append("Every inventoried claim is verified.")
    for area, found in _gaps_by_area(claims).items():
        lines += [f'<a id="area-{area}"></a>', "", f"## {area.title()}", ""]
        for claim in found:
            lines += [f'<a id="{claim.id}"></a>', "", f"**{claim.id}** — {claim.summary}", ""]
            for surface in claim.surfaces:
                lines.append(f"- `{surface.path}`")
            lines.append("")
    lines.append(DOC_END)
    return "\n".join(lines) + "\n"


def render_block(claims: list[Claim]) -> str:
    """Render the marked README summary block."""

    total, detail = _counts(claims)
    groups = _gaps_by_area(claims)
    links = ", ".join(f"[{area}](remaining-work.md#area-{area})" for area in groups)
    body = f"Open gaps: {total}" + (f" ({detail})" if detail else "")
    if links:
        body += f". By area: {links}."
    return "\n".join([BLOCK_START, body, BLOCK_END])


def replace_block(text: str, block: str) -> str:
    """Replace the marked region in ``text`` with ``block``."""

    for marker in (BLOCK_START, BLOCK_END):
        found = text.count(marker)
        if found != 1:
            raise ValueError(f"{marker} must appear exactly once, found {found}")
    start = text.index(BLOCK_START)
    end = text.index(BLOCK_END) + len(BLOCK_END)
    return text[:start] + block + text[end:]
